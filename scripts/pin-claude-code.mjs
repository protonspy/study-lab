// Pin the Claude Code release the app installs: download the release manifest and its signature,
// verify the signature with gpg against Anthropic's release key, and write the version and each
// binary's SHA-256 to src/main/claude/pinned.ts.
//
//     npm run pin-claude-code -- 2.1.310

import { execFileSync } from "node:child_process"
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import path from "node:path"

const REPOSITORY = "https://downloads.claude.ai/claude-code-releases"
const KEY = "https://downloads.claude.ai/keys/claude-code.asc"
// The fingerprint published on Claude Code's setup page.
const FINGERPRINT = "31DDDE24DDFAB679F42D7BD2BAA929FF1A7ECACE"
const PLATFORMS = ["win32-x64", "win32-arm64", "darwin-x64", "darwin-arm64"]
const TARGET = path.join(import.meta.dirname, "..", "src", "main", "claude", "pinned.ts")

const version = process.argv[2]
if (!/^\d+\.\d+\.\d+$/.test(version ?? "")) {
  console.error("usage: npm run pin-claude-code -- <version>, e.g. 2.1.310")
  process.exit(1)
}

async function download(url) {
  const res = await fetch(url)
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`)
  return Buffer.from(await res.arrayBuffer())
}

const dir = mkdtempSync(path.join(tmpdir(), "pin-claude-code-"))
try {
  writeFileSync(path.join(dir, "key.asc"), await download(KEY))
  writeFileSync(path.join(dir, "manifest.json"), await download(`${REPOSITORY}/${version}/manifest.json`))
  writeFileSync(path.join(dir, "manifest.json.sig"), await download(`${REPOSITORY}/${version}/manifest.json.sig`))

  // A keyring for this run only, so the check never depends on what the machine's gpg already trusts.
  // Paths relative to the folder: Git for Windows' gpg cannot read absolute Windows paths.
  const gpg = (...args) => execFileSync("gpg", ["--homedir", ".", "--batch", "--no-tty", ...args], { cwd: dir, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] })
  gpg("--import", "key.asc")
  const status = gpg("--status-fd", "1", "--verify", "manifest.json.sig", "manifest.json")
  const valid = status.split("\n").find((l) => l.startsWith("[GNUPG:] VALIDSIG "))
  const signer = valid?.split(" ")[11] ?? valid?.split(" ")[2]
  if (!valid || signer !== FINGERPRINT) throw new Error(`the manifest signature does not match key ${FINGERPRINT}`)

  const manifest = JSON.parse(readFileSync(path.join(dir, "manifest.json"), "utf8"))
  if (manifest.version !== version) throw new Error(`the manifest is for version ${manifest.version}`)
  const platforms = {}
  for (const p of PLATFORMS) {
    const item = manifest.platforms?.[p]
    if (!/^[0-9a-f]{64}$/.test(item?.checksum ?? "")) throw new Error(`${p} has no checksum`)
    platforms[p] = { binary: item.binary, sha256: item.checksum, size: item.size }
  }
  const pinned = { version, repository: REPOSITORY, platforms }
  writeFileSync(
    TARGET,
    `import type { Pinned } from "./install"\n\n/* Generated by scripts/pin-claude-code.mjs from the release manifest, its gpg signature checked. */\n\nexport const PINNED: Pinned = ${JSON.stringify(pinned, null, 2)}\n`,
  )
  console.log(`Claude Code ${version} pinned in src/main/claude/pinned.ts`)
} finally {
  rmSync(dir, { recursive: true, force: true })
}
